def compute_f_profiles(X: np.ndarray) -> np.ndarray:
    X = X / np.sum(X, axis=1)[:, np.newaxis]
    alpha = []
    for i in range(len(X)):
        w, _ = scipy.optimize.nnls(F_PROFILES.T, X[i, :])
        w = w / np.sum(w)
        alpha.append(w)
    return np.asarray(alpha)


def cgnngc_ratios(X: np.ndarray) -> np.ndarray:
    X = X / np.sum(X, axis=1)[:, np.newaxis]
    # CGN/NCG motif ratio
    idx_cgn, idx_ncg = [], []
    for k in range(256):
        motif = uint8_motif_to_str(k)
        if motif[:2] == 'CG':
            idx_cgn.append(k)
        elif motif[1:3] == 'CG':
            idx_ncg.append(k)
    idx_cgn, idx_ncg = np.asarray(idx_cgn), np.asarray(idx_ncg)
    return np.sum(X[:, idx_cgn], axis=1) / np.sum(X[:, idx_ncg], axis=1)


def semfar_scores(X: np.ndarray) -> np.ndarray:
    X = X / np.sum(X, axis=1)[:, np.newaxis]
    return np.sum(X * REFERENCE_GENOME_END_MOTIF_FREQS[np.newaxis, :], axis=1)


def end_motif_diversity(X: np.ndarray) -> np.ndarray:
    X = X / np.sum(X, axis=1)[:, np.newaxis]
    return np.sum(np.abs(X - REFERENCE_GENOME_END_MOTIF_FREQS[np.newaxis, :]) ** (1 / 2), axis=1) ** 2


def str_motif_to_mask(motif: str) -> np.ndarray:
    mask = np.zeros(256, dtype=bool)
    for k in range(256):
        s = uint8_motif_to_str(k)
        valid = True
        for c1, c2 in zip(s, motif):
            if c2 == 'N':
                continue
            if c1 != c2:
                valid = False
                break
        mask[k] = valid
    return mask


def str_motif_to_uint8(motif: str) -> int:
    i = 0
    i += BASES_DICT[motif[0]] << 6
    i += BASES_DICT[motif[1]] << 4
    i += BASES_DICT[motif[2]] << 2
    i += BASES_DICT[motif[3]]
    return i


def uint8_motif_to_str(motif: int) -> str:
    s = BASES[(motif & 0xC0) >> 6]
    s += BASES[(motif & 0x30) >> 4]
    s += BASES[(motif & 0x0C) >> 2]
    s += BASES[(motif & 0x03)]
    return s


def one_hot_encode_uint8_motif(motif: int) -> np.ndarray:
    s = uint8_motif_to_str(motif)
    ohe = []
    for i in range(4):
        ohe += BASES_OHE[s[i]]
    ohe = np.asarray(ohe)
    assert len(ohe) == 16
    return ohe


def end_motif_importances(motif_freqs: np.ndarray):
    assert len(motif_freqs) == 256
    X = np.asarray([one_hot_encode_uint8_motif(i) for i in range(len(motif_freqs))])
    model = Ridge(alpha=0.01, fit_intercept=False)
    model.fit(X, motif_freqs)
    return model.coef_


class EndMotifHistograms:

    def __init__(self, X: np.ndarray) -> None:
        assert len(X.shape) == 2
        assert np.all(X >= 0)
        self.X: np.ndarray = X / np.sum(X, axis=1)[:, np.newaxis]
        self.n: int = int(self.X.shape[0])
        self.m: int = int(self.X.shape[1])

    def __getitem__(self, motif: str) -> np.ndarray:
        mask = np.zeros(self.m, dtype=bool)
        for k in range(self.m):
            s = uint8_motif_to_str(k)
            valid = True
            for c1, c2 in zip(s, motif):
                if c2 == 'N':
                    continue
                if c1 != c2:
                    valid = False
                    break
            mask[k] = valid
        return np.sum(self.X[:, mask], axis=1)
